def run_notice_checks(language):
    """Real model translation of configured text; no participant data or services."""
    from maya.framework.conversation import responses
    from maya.agents.health_rag.config import load_health_rag_config
    from maya.agents.health_rag.agent import RetrieveLocalLiterature
    from maya.framework.integrations.biomarkers import BiomarkerConfig, BiomarkerService
    from maya.framework.ontology import get_ontology_registry
    from maya.tests.test_health_rag_retrieval import StubRetriever
    from system_test import check_row

    rows = []
    def record(name, checks, samples=(), sources=(), **evidence):
        area, requirement = LOCALIZATION_REQUIREMENTS[name]
        rows.append(check_row(name, area, requirement, checks, language_samples=list(samples),
                              translation_sources=list(sources), **evidence))

    source, policy = responses.load_response_policy(), responses.response_policy(language)
    fields = responses.ResponseMessages.model_fields
    record("notices.policy", {
        "all_messages_present": all(getattr(policy, key).strip() for key in fields),
        "machine_instruction_unchanged": policy.health_output_instruction == source.health_output_instruction,
        "delay_unchanged": policy.health_processing_delay_seconds == source.health_processing_delay_seconds,
        "privacy_url_unchanged": policy.privacy_notice_url == source.privacy_notice_url,
    }, [getattr(policy, key) for key in fields], [getattr(source, key) for key in fields])

    answer = "Doxorubicin — 116/67 mmHg; 49 bpm."
    citation = {"title": "Original study title", "source_path": "/private/source.pdf", "page_number": 2}
    shown = responses.health_presentation(answer, [citation, citation, {}], language)
    empty = responses.health_presentation(answer, [], language)
    record("notices.presentation", {
        "answer_unchanged": shown["answer_text"] == answer,
        "references_preserved_and_deduplicated": len(shown["references"]) == 2 and shown["references"][0]["title"] == citation["title"],
        "source_path_private": "/private/" not in shown["display_text"],
        "localized_page_and_unknown_source": policy.page_label + " 3" in shown["display_text"] and policy.unknown_source_label in shown["display_text"],
        "disclaimer_once": shown["display_text"].count(policy.health_disclaimer) == 1,
        "speech_is_answer_plus_disclaimer": shown["speech_text"] == answer + "\n\n" + policy.health_disclaimer,
        "empty_references_localized": policy.no_references_text in empty["display_text"],
    }, presentation=shown, empty_presentation=empty)
    opening = responses.opening_response(language)
    record("notices.opening", {"display_disclosure": policy.ai_disclosure in opening.display_text,
                              "speech_disclosure_only": opening.speech_text == policy.ai_disclosure},
           [opening.speech_text], [source.ai_disclosure])

    health = load_health_rag_config().messages
    localized_health = responses.localize_messages(health, language)
    no_evidence = RetrieveLocalLiterature(StubRetriever([]), None).before_model(
        {"standalone_question": "Unmatched topic", "response_language": language}, None)
    record("notices.health_fallbacks", {
        "middleware_uses_localized_no_evidence": no_evidence["messages"][0].content == localized_health.no_evidence,
        "no_unsupported_answer": no_evidence["jump_to"] == "end",
    }, list(localized_health.model_dump().values()), list(health.model_dump().values()))

    # Build only the label boundary; never instantiate a live FHIR provider.
    settings = BiomarkerConfig.model_validate_json((ROOT / "maya/framework/integrations/biomarkers/config.json").read_text())
    service = BiomarkerService(settings, None)
    labelled = service.label_answer(answer, [{"synthetic": True, "observations": [{}]}], language)
    notice = responses.localize_text(settings.synthetic_notice, language)
    record("notices.synthetic_label", {
        "translated_notice_only": labelled == notice + "\n\n" + answer if notice else labelled == answer,
        "real_data_not_labelled": service.label_answer(answer, [{"synthetic": False, "observations": [{}]}], language) == answer,
    }, [notice] if notice else [], [settings.synthetic_notice] if notice else [])
    pending = get_ontology_registry().runtime["memory_policy"]["recovery_unavailable_text"]
    translated = responses.localize_text(pending, language)
    record("notices.memory_pending", {"message_present": bool(translated.strip())}, [translated], [pending])
    return rows


def fixture_name_present(text, name, language):
    """Recognize controlled personal/place names in user-facing fixture answers.

    Greek transliterations preserve the named person/city. Medication spellings,
    identifiers, unit symbols and stored profile fields retain their own stricter
    assertions; this is not a general translation or semantic evaluator.
    """
    aliases = {"el": {"Sam": ("Σαμ",), "York": ("Γιορκ", "Υόρκη"),
                      "Bath": ("Μπαθ",), "Bristol": ("Μπρίστολ",)}}
    candidates = (name, *aliases.get(language, {}).get(name, ()))
    return any(candidate.casefold() in text.casefold() for candidate in candidates)


def memory_content_checks(saved, recalled, other):
    """Check the controlled appointment fixture, not just a nonempty reply.

    These stems accept common translations of nervous/anxious in the configured
    test languages, and English records produced by the memory extractor.
    They are a narrow fixture assertion, not a general semantic evaluator.
    """
    stems = ("nerv", "anxi", "anxie", "emoți", "emoti", "hermost", "jänn", "ahdist", "ansios", "ansia",
             "aufgereg", "angespann", "ängst", "αγχ", "άγχ", "νευρ", "ανησυχ", "ανήσυχ")
    def contains_experience(value):
        text = str(value).casefold()
        return any(stem in text for stem in stems)
    return {
        "experience_saved": any(contains_experience(item.get("content", "")) for item in saved),
        "recall_answers_instead_of_writing": recalled["route"] == "direct_answer",
        "recalled_experience": contains_experience(recalled["answer"]),
        "no_other_participant_experience_disclosure": not contains_experience(other["answer"]),
    }


def run_workflows(language, directory, *, selected=()):
    if set(selected) - WORKFLOW_REQUIREMENTS.keys():
        raise ValueError("Unknown workflow selection.")
    requirements = {name: detail for name, detail in WORKFLOW_REQUIREMENTS.items() if not selected or name in selected}
    configured = json.loads((ROOT / "maya/agents/config.jsonl").read_text(encoding="utf-8"))
    if set(configured["phyxio_exercise_agent"]["tools"]) != set(TOOLS.values()):
        raise ValueError("The configured exercise tools changed; update the acceptance scenarios and native prompts.")
    from langchain_core.messages import HumanMessage
    from langchain_core.runnables import RunnableLambda
    from langgraph.store.memory import InMemoryStore
    from langgraph.checkpoint.memory import InMemorySaver
    from maya.framework.conversation.personalization import SessionConfig
    from maya.framework.memory.ontology import OntologyMemoryService
    from maya.framework.supervisor import factory
    from maya.agents.phyxio_exercise_agent import agent as exercise, phyxio_sessions
    from maya.tests.test_fhir_biomarkers import configured_service, observation, records
    from maya.tests.test_phyxio_sessions import configured_service as exercise_config, history_reader
    from maya.tests.test_phyxio_offline_integration import make_service
    from system_test import check_row, complete_cases, write_json, redact

    prompts, rows, workers = PROMPTS[language], [], []
    store = InMemoryStore()
    routing_decisions = []
    memory_proposals = []
    structured_output = factory.model_call

    def observed_routing(model, schema=None, **kwargs):
        runnable = structured_output(model, schema, **kwargs)
        if schema is factory.MemoryVerification:
            return runnable | RunnableLambda(capture_memory)
        if schema not in (factory.SupervisorRouteDecision, factory.HealthRouteGuardDecision):
            return runnable
        def capture(decision):
            routing_decisions.append({"schema": schema.__name__, **decision.model_dump()})
            return decision
        return runnable | RunnableLambda(capture)

    def capture_memory(result):
        memory_proposals.append({"schema": type(result).__name__, **result.model_dump()})
        return result

    with tempfile.TemporaryDirectory(prefix="maya-acceptance-fixtures-") as folder, ExitStack() as stack:
        folder = Path(folder)
        biomarkers = configured_service(folder)
        biomarkers.provider.synthetic = True
        biomarkers.config.patient_map = {}
        exercise_config(folder)
        mirror = make_service()
        reader = history_reader()
        mirror.session_history_reader.return_value = reader

        def fixture_get(kind, **params):
            if params.get("subject") != "synthetic-patient":
                raise ValueError("Test boundary rejected an unexpected patient ID.")
            item = observation(kind)
            if kind != "blood-pressure":
                item.pop("component")
                item["valueQuantity"] = {"value": 72.4 if kind == "body-weight" else 73,
                                         "unit": "kg" if kind == "body-weight" else "bpm"}
            return records(item)

        biomarkers.provider.client.get.side_effect = fixture_get
        def memory_factory(**kwargs):
            worker = OntologyMemoryService(**kwargs, register_shutdown=False)
            workers.append(worker)
            return worker

        stack.enter_context(patch.object(factory, "get_postgres_memory", return_value=(store, InMemorySaver())))
        stack.enter_context(patch.object(factory, "model_call", new=observed_routing))
        stack.enter_context(patch.object(factory, "memory_extractor", factory.memory_extractor | RunnableLambda(capture_memory)))
        stack.enter_context(patch.object(factory, "profile_extractor", factory.profile_extractor | RunnableLambda(capture_memory)))
        stack.enter_context(patch.object(factory, "OntologyMemoryService", side_effect=memory_factory))
        stack.enter_context(patch.object(exercise, "get_phyxio_service", return_value=mirror))
        stack.enter_context(patch.object(phyxio_sessions, "get_phyxio_service", return_value=mirror))
        stack.enter_context(patch.object(exercise, "ROUTINE_ID", ""))
        stack.enter_context(patch.dict(os.environ, {"MAYA_EXERCISE_SESSION_CONFIG": str(folder / "exercise.json")}))
        graph = factory.build_supervisor(biomarker_service=biomarkers)

        def turn(question, user, *, response_language=None):
            biomarkers.config.patient_map[user] = "synthetic-patient"
            session = SessionConfig(user_id=user, preferences={"response_language": response_language or language})
            config = session.graph_config()
            biomarkers.provider.client.get.reset_mock()
            routing_decisions.clear()
            memory_proposals.clear()
            mirror.reset_mock(); reader.reset_mock()
            result = graph.invoke({"messages": [HumanMessage(content=question)]}, config)
            for worker in workers:
                with worker._condition:
                    if not worker._condition.wait_for(lambda: not worker._scheduled_jobs, timeout=120):
                        raise TimeoutError("Background memory verification did not complete.")
            message = result["messages"][-1]
            return {"prompt": question, "answer": message.content, "route": result.get("route_type"),
                    "routing_decisions": list(routing_decisions),
                    "memory_proposals": list(memory_proposals),
                    "metadata": message.additional_kwargs,
                    "interrupts": [item.value for item in graph.get_state(config).interrupts],
                    "biomarkers": result.get("biomarker_results", []),
                    "sdk_calls": [{"resource": call.args[0], **call.kwargs} for call in biomarkers.provider.client.get.call_args_list],
                    "exercise_calls": [str(call) for call in mirror.mock_calls],
                    "action_counts": {name: getattr(mirror, name).call_count for name in ("show_routine", "calibrate_routine", "run_routine")},
                    "history_calls": reader.getSessionList.call_count}

        def record(name, checks, *turns, **evidence):
            area, requirement = WORKFLOW_REQUIREMENTS[name]
            samples = [text for entry in turns for text in (entry["interrupts"] or [entry["answer"]])]
            row = check_row(name, area, requirement, checks, language_samples=samples, turns=list(turns), **evidence)
            rows.append(row)
            write_json(directory / "workflow-evidence.json", rows)
            print(json.dumps({"case": name, "status": row["status"], "checks": row["checks"]}), flush=True)

        def completed(entry):
            return bool(entry["answer"]) and not entry["interrupts"]

        def health_answer(entry):
            presentation = entry["metadata"].get("presentation", {})
            references = presentation.get("references", [])
            spoken = presentation.get("speech_text", "")
            return entry["route"] == "health_rag" and completed(entry) and bool(references) and all(
                reference["file_name"] not in spoken for reference in references if reference.get("file_name"))

        def run_case(name):
            # LangGraph namespace segments reject dots; scenario IDs are labels,
            # not participant identifiers.
            user = f"acceptance-{language}-{name.replace('.', '-')}"
            if name == "native.conversation":
                result = turn(prompts["hello"], user)
                record(name, {"direct_route": result["route"] == "direct_answer", "completed": completed(result),
                              "no_participant_tools": not result["sdk_calls"] and not result["exercise_calls"]}, result)
            elif name == "native.health":
                result = turn(prompts["health"], user)
                record(name, {"evidence_and_display_only_references": health_answer(result),
                              "no_patient_lookup": not result["sdk_calls"]}, result)
            elif name in ("native.pressure", "native.weight"):
                key = name.split(".")[-1]
                kind = "blood-pressure" if key == "pressure" else "body-weight"
                result = turn(prompts[key], user)
                expected_values = ("134", "82", "mmHg") if key == "pressure" else ("kg",)
                record(name, {"biomarker_route": result["route"] == "biomarkers", "completed": completed(result),
                              "scoped_correct_resource": result["sdk_calls"] == [{"resource": kind, "subject": "synthetic-patient"}],
                              "verified_result": bool(result["biomarkers"]) and result["biomarkers"][0]["status"] == "ok",
                              "values_units": all(token in result["answer"] for token in expected_values) and
                              (key == "pressure" or any(value in result["answer"] for value in ("72.4", "72,4")))}, result)
            elif name == "measurement.unsupported":
                result = turn(prompts["temperature"], user)
                record(name, {"response_or_clarification": bool(result["answer"] or result["interrupts"]), "no_substituted_measurement_lookup": not result["sdk_calls"],
                              "identified_as_unsupported": any(item["status"] == "unsupported_measurement" for item in result["biomarkers"]),
                              "no_weight_value": "72.4" not in result["answer"] and "72,4" not in result["answer"]}, result)
            elif name == "measurement.missing_units":
                def unitless(kind, **params):
                    item = observation(kind); item.pop("component")
                    item["valueQuantity"] = {"value": 72.4}
                    return records(item)
                biomarkers.provider.client.get.side_effect = unitless
                result = turn(prompts["weight"], user)
                record(name, {"lookup_attempted": bool(result["sdk_calls"]),
                              "unavailable": bool(result["biomarkers"]) and result["biomarkers"][0]["status"] == "unavailable",
                              "no_unverified_value": "72.4" not in result["answer"] and "72,4" not in result["answer"]}, result)
            elif name == "measurement.partial_results":
                biomarkers.provider.client.get.side_effect = lambda kind, **params: [] if kind == "body-weight" else fixture_get(kind, **params)
                result = turn("Show my latest blood pressure and body weight, with dates and units, without interpreting them.", user)
                record(name, {"both_resources_requested": {item["resource"] for item in result["sdk_calls"]} == {"blood-pressure", "body-weight"},
                              "independent_lookup_outcomes": {tuple(item["requested"]): item["status"] for item in result["biomarkers"]}
                              == {("blood_pressure",): "ok", ("body_weight",): "unavailable"},
                              "available_pressure_retained": all(token in result["answer"] for token in ("134", "82", "mmHg")),
                              "no_invented_weight": "72.4" not in result["answer"] and "72,4" not in result["answer"]}, result)
            elif name.startswith("routing.fact_only_"):
                from maya.tests.live_supervisor_routing_scenarios import SCENARIOS
                scenario = next(item for item in SCENARIOS if item.name == name.removeprefix("routing."))
                result = turn(scenario.text, user)
                selected = result["routing_decisions"][0]["selected_ontology_models"]
                record(name, {"direct_acknowledgement": result["route"] == scenario.expected_route and completed(result),
                              "relevant_ontology_selected": set(scenario.expected_models) <= set(selected),
                              "no_participant_lookup": not result["sdk_calls"] and not result["exercise_calls"]}, result)
            elif name.startswith("native.tool."):
                key = name.split(".")[-1]
                result = turn(prompts[key], user)
                action = {"show": "show_routine", "calibrate": "calibrate_routine", "start": "run_routine"}.get(key)
                expected_actions = {method: int(method == action) for method in result["action_counts"]}
                record(name, {"exercise_route": result["route"] == "phyxio_exercise_agent", "completed": completed(result),
                              "correct_tool": result["metadata"].get("executed_tool") == TOOLS[key],
                              "only_intended_action": result["action_counts"] == expected_actions,
                              "no_biomarker_lookup": not result["sdk_calls"],
                              "history_read_when_requested": key not in ("history", "feedback") or result["history_calls"] > 0}, result)
            elif name.startswith("negated.tool."):
                key = name.split(".")[-1]
                operation = {"show": "show my exercise routine", "calibrate": "calibrate my exercise routine",
                             "start": "start my exercise routine", "list": "list my exercises",
                             "history": "access my exercise history", "feedback": "review my latest exercise session"}[key]
                result = turn(f"Do not {operation}. I am not requesting any exercise action or record lookup.", user)
                record(name, {"completed": completed(result), "no_exercise_operation": not result["exercise_calls"],
                              "no_selected_tool": not result["metadata"].get("executed_tool")}, result)
            elif name == "exercise.safety_hold":
                result = turn(prompts["unsafe_start"], user)
                record(name, {"completed": completed(result), "no_action": not any(result["action_counts"].values()),
                              "no_session_lookup": result["history_calls"] == 0}, result)
            elif name == "memory.no_write":
                questions = [
                    "If I visited Bristol tomorrow, would you remember that? This is hypothetical.",
                    "Here is a fictional example, not a fact about me: 'I live in York and visited Bristol yesterday.' Explain the sentence without saving it.",
                    "I visited Bristol yesterday, but do not save this in my memory or profile.",
                    "My friend Alex visited Bristol yesterday. I am asking about Alex, not reporting my own experience.",
                ]
                turns = [turn(question, user) for question in questions]
                record(name, {"completed": all(completed(item) for item in turns),
                              "no_memory_written": not store.search(("memory", user)),
                              "no_profile_written": not store.search(("profile", user)),
                              "no_participant_lookup": not any(item["sdk_calls"] or item["exercise_calls"] for item in turns)}, *turns)
            elif name in ("memory.correct_and_recall", "profile.correct_and_recall"):
                key = name.split(".")[0]
                first = turn("I visited Bristol yesterday. Please remember that." if key == "memory" else
                             "My name is Sam and I live in York. Please remember that.", user)
                before = {item.key: item.value for item in store.search((key, user))}
                corrected = turn("Correction: I visited Bath yesterday, not Bristol. Please update that memory." if key == "memory" else
                                 "I moved to Bath. My name is still Sam. Please update my profile.", user)
                after = {item.key: item.value for item in store.search((key, user))}
                recalled = turn("Which city did I say I visited yesterday?" if key == "memory" else
                                "What is my name and where do I live?", user)
                repeated = turn("I visited Bath yesterday. Please remember that." if key == "memory" else
                                "My name is Sam and I live in Bath. Please remember that.", user)
                final = {item.key: item.value for item in store.search((key, user))}
                checks = {"initial_record_saved": len(before) == 1,
                          "same_record_updated": bool(after) and set(before) == set(after) and before != after,
                          "correction_saved": any("Bath" in str(item.get("content" if key == "memory" else "location", "")) for item in after.values()),
                          "recalled_correction": recalled["route"] == "direct_answer" and fixture_name_present(recalled["answer"], "Bath", language),
                          "repeat_does_not_duplicate": set(final) == set(after) and len(final) == 1,
                          "completed": all(completed(item) for item in (first, corrected, recalled, repeated))}
                if key == "profile":
                    checks["name_preserved"] = any(item.get("name") == "Sam" for item in after.values()) and fixture_name_present(recalled["answer"], "Sam", language)
                record(name, checks, first, corrected, recalled, repeated, before=before, after=after, final=final)
            elif name == "memory.mixed_and_language_change":
                first = turn("I visited Bristol yesterday. Please remember that.", user, response_language="en")
                before = {item.key: item.value for item in store.search(("memory", user))}
                target = language if language != "en" else "fi"
                mixed = turn("Which city did I visit yesterday? Also, I enjoyed painting today; please remember that new fact.",
                             user, response_language=target)
                after = {item.key: item.value for item in store.search(("memory", user))}
                record(name, {"initial_record_saved": len(before) == 1,
                              "previous_memory_preserved": all(after.get(key) == value for key, value in before.items()),
                              "only_new_assertion_saved": len(after) == len(before) + 1 and any(
                                  "painting" in item.get("content", "").lower()
                                  and "Which city" not in item.get("content", "") for key, item in after.items() if key not in before),
                              "answers_recall": fixture_name_present(mixed["answer"], "Bristol", target) and completed(mixed)},
                       mixed, first_turn=first, before=before, after=after, expected_language=target)
            elif name in ("profile.save_and_recall", "memory.save_and_recall"):
                key = name.split(".")[0]
                first = turn(prompts[key], user)
                saved = [item.value for item in store.search((key, user))]
                before_recall = {item.key: item.value for item in store.search((key, user))}
                recalled = turn(prompts["recall_" + key], user)
                after_recall = {item.key: item.value for item in store.search((key, user))}
                other_user = user + "-other"
                other = turn(prompts["recall_" + key], other_user)
                checks = {"expected_write_route": first["route"] == ("user_profile" if key == "profile" else "general_memory"),
                          "record_saved": bool(saved), "recall_completed": completed(recalled),
                          "recall_store_unchanged": before_recall == after_recall,
                          "other_participant_store_empty": not store.search((key, other_user)),
                          "no_health_record_lookup": not recalled["sdk_calls"] and not other["sdk_calls"]}
                if key == "profile":
                    checks.update(correct_profile_saved=any(item.get("name") == "Sam" and "York" in (item.get("location") or "") for item in saved),
                                  recalled_values=all(fixture_name_present(recalled["answer"], name, language) for name in ("Sam", "York")),
                                  no_other_participant_disclosure=not any(fixture_name_present(other["answer"], name, language) for name in ("Sam", "York")))
                else:
                    checks.update(memory_content_checks(saved, recalled, other))
                record(name, checks, first, recalled, other, saved_records=saved,
                       records_after_recall=after_recall,
                       other_participant_records=[item.value for item in store.search((key, other_user))])
            else:
                raise ValueError("Unknown workflow scenario: " + name)

        try:
            for name in requirements:
                try:
                    run_case(name)
                except Exception as error:
                    rows.append({"id": name, "area": WORKFLOW_REQUIREMENTS[name][0], "requirement": WORKFLOW_REQUIREMENTS[name][1],
                                 "status": "ERROR", "reason": redact(f"{type(error).__name__}: {error}")[:1200]})
                    write_json(directory / "workflow-evidence.json", rows)
                finally:
                    biomarkers.provider.client.get.side_effect = fixture_get
        finally:
            for worker in workers:
                worker.close()
    return complete_cases(rows, requirements)


